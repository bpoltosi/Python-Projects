import math

print (math.sqrt(8)) #raiz quadrada
print (math.pow(2,3)) #potenciação 2**3
print (math.fabs(-10)) #módulo "|-10|"
print (math.factorial(42)) #fatorial "42!"
print (math.gcd(2,20)) #maior divisor comum
print (math.ceil(8.8)) #arredonda pro proximo inteiro
print (math.trunc(6.76544)) #despreza casas decimais
print (math.sin(90) + math.cos(90)) #seno e coseno
print (math.pi) #pi